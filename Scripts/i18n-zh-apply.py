for path in glob.glob('Packages/ApelinAgent/Sources/**/*.swift', recursive=True):
    if 'ToolCatalog' in path: continue
    s = open(path, encoding='utf-8').read()
    orig = s
    for a, b in M.items():
        if a in s:
            s = s.replace(a, b)
    if s != orig:
        open(path, 'w', encoding='utf-8').write(s)
        changed += 1
